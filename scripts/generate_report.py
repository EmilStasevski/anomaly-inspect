#!/usr/bin/env python
"""Generate docs/results.md and the README tables from MLflow and the benchmark outputs."""

from __future__ import annotations

import json
import shutil
import tempfile
from pathlib import Path
from typing import Any

import mlflow

from anomaly_inspect.charts import auroc_chart, calibrated_f1_chart, how_it_works, latency_chart
from anomaly_inspect.data import CATEGORIES, FOCUS_CATEGORIES
from anomaly_inspect.report import (
    category_table,
    environment_line,
    export_table,
    focus_table,
    highlights,
    latency_table,
    replace_block,
    summary_table,
)
from anomaly_inspect.tracking import configure_tracking

FIGURES = Path("docs/figures")
RESULTS = Path("docs/results.md")
READMES = {"en": Path("README.md"), "de": Path("README.de.md")}
QUALITY_METRICS = [
    ("Image AUROC", "image_auroc"),
    ("Pixel AUROC", "pixel_auroc"),
    ("AUPRO", "aupro"),
]
DECISION_METRICS = [
    ("F1 max", "f1_max"),
    ("F1 calibrated", "f1_calibrated"),
    ("Recall", "recall_calibrated"),
    ("False rejects", "false_reject_rate_calibrated"),
]


def latest_summary(client: mlflow.MlflowClient, family: str) -> tuple[Any, dict[str, Any]]:
    """The newest complete summary run. Partial runs on a few categories do not qualify."""
    experiment = client.get_experiment_by_name(family)
    if experiment is None:
        raise RuntimeError(f"no MLflow experiment {family!r}. Run `make train` and `make eval`.")
    runs = client.search_runs(
        [experiment.experiment_id],
        filter_string=(
            "tags.run_type = 'summary' and attributes.status = 'FINISHED' "
            f"and params.n_categories = '{len(CATEGORIES)}'"
        ),
        order_by=["attributes.start_time DESC"],
        max_results=1,
    )
    if not runs:
        raise RuntimeError(f"no complete summary run for {family!r}")
    run = runs[0]
    summary = mlflow.artifacts.load_dict(f"runs:/{run.info.run_id}/summary/per_category.json")
    return run, summary


def provenance_row(name: str, run: Any) -> str:
    commit = run.data.tags["git_commit"][:12]
    return f"| {name} | `{run.info.run_id}` | `{commit}` | {run.data.params['seed']} |"


def copy_figures(family: str, run_ids: dict[str, str]) -> None:
    FIGURES.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as tmp:
        for category in FOCUS_CATEGORIES:
            name = f"{family}_{category}.png"
            local = mlflow.artifacts.download_artifacts(
                run_id=run_ids[category], artifact_path=f"heatmaps/{name}", dst_path=tmp
            )
            shutil.copy(local, FIGURES / name)


def main() -> None:
    configure_tracking()
    client = mlflow.MlflowClient()
    baseline_run, baseline = latest_summary(client, "baseline")
    patchcore_run, patchcore = latest_summary(client, "patchcore")
    copy_figures("baseline", baseline["run_ids"])
    copy_figures("patchcore", patchcore["run_ids"])

    bench = json.loads(Path("results/bench.json").read_text())
    export = json.loads(Path("results/export.json").read_text())
    base, core = baseline["per_category"], patchcore["per_category"]

    summary = summary_table(base, core)
    latency = latency_table(bench)
    parity = export_table(export)
    environment = environment_line(bench)

    figures = "\n\n".join(
        f"### {category}\n\n![PatchCore on {category}](figures/patchcore_{category}.png)\n\n"
        f"![Baseline on {category}](figures/baseline_{category}.png)"
        for category in FOCUS_CATEGORIES
    )
    RESULTS.write_text(
        f"""# Results

Generated by `make report`. Do not edit by hand.

## Provenance

| Family | MLflow summary run | Git commit | Seed |
| --- | --- | --- | ---: |
{provenance_row("Baseline", baseline_run)}
{provenance_row("PatchCore", patchcore_run)}

## Summary

{summary}

"Focus 6" means {", ".join(FOCUS_CATEGORIES)}.

## Detection and localisation per category

{category_table(base, core, FOCUS_CATEGORIES, QUALITY_METRICS)}

All categories:

{category_table(base, core, CATEGORIES, QUALITY_METRICS)}

## Decisions per category

"F1 max" chooses the best threshold using test labels, which is impossible in production. The other
columns use a threshold calibrated on held-out good training images only (mean + 3 standard
deviations of their scores).

{category_table(base, core, CATEGORIES, DECISION_METRICS)}

## Latency

{environment}

{latency}

## ONNX parity

Maximum absolute difference between PyTorch and ONNX Runtime on real test images. Tolerances:
{export["score_tolerance"]} for scores, {export["map_tolerance"]} for anomaly map pixels. Scores are
in the tens.

{parity}

## Heatmaps

Images are excerpts of MVTec AD, adapted, under CC BY-NC-SA 4.0. Examples are selected by a fixed
rule that does not look at scores: the first two good images and the first image of up to four
defect types.

{figures}
"""
    )

    for language, path in READMES.items():
        auroc_chart(base, core, FIGURES / f"chart_auroc_{language}.png", language)
        calibrated_f1_chart(base, core, FIGURES / f"chart_f1_{language}.png", language)
        latency_chart(bench, FIGURES / f"chart_latency_{language}.png", language)
        how_it_works(FIGURES / f"how_it_works_{language}.png", language)

        readme = path.read_text()
        for block, content in {
            "highlights": highlights(base, core, bench, export, language),
            "summary": summary_table(base, core, language),
            "focus": focus_table(base, core, language),
            "latency": (f"{environment_line(bench, language)}\n\n{latency_table(bench, language)}"),
            "parity": export_table(export, language),
        }.items():
            readme = replace_block(readme, block, content)
        path.write_text(readme)
    print(f"Wrote {RESULTS} and updated the READMEs")


if __name__ == "__main__":
    main()
